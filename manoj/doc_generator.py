def _set_slide_bg(slide, color: PRGBColor) -> None:
    fill = slide.background.fill
    fill.solid()
    fill.fore_color.rgb = color


def _pptx_findings_deck(prs: Presentation, content: dict) -> None:
    """Inspection findings presentation deck — dark themed."""
    # Title slide
    slide = prs.slides.add_slide(prs.slide_layouts[6])
    _set_slide_bg(slide, _SOVEREIGN_BLUE)
    tb = slide.shapes.add_textbox(PInches(1), PInches(2), PInches(8), PInches(1.5))
    tf = tb.text_frame
    tf.word_wrap = True
    p = tf.add_paragraph()
    p.text = content.get("title", "Inspection Findings")
    p.font.size = PPt(40); p.font.bold = True; p.font.color.rgb = _WHITE
    p.alignment = PP_ALIGN.CENTER
    p2 = tf.add_paragraph()
    p2.text = content.get("subtitle", f"Date: {datetime.now().strftime('%B %d, %Y')}")
    p2.font.size = PPt(18); p2.font.color.rgb = _SOVEREIGN_ACCENT
    p2.alignment = PP_ALIGN.CENTER

    # One slide per finding
    for i, finding in enumerate(content.get("findings", []), 1):
        slide = prs.slides.add_slide(prs.slide_layouts[6])
        _set_slide_bg(slide, _SOVEREIGN_BLUE)
        badge = slide.shapes.add_textbox(PInches(0.5), PInches(0.3), PInches(1), PInches(0.5))
        badge.text_frame.text = f"#{i}"
        badge.text_frame.paragraphs[0].font.color.rgb = _SOVEREIGN_ACCENT
        badge.text_frame.paragraphs[0].font.size = PPt(14)
        hb = slide.shapes.add_textbox(PInches(0.5), PInches(0.8), PInches(9), PInches(1))
        hb.text_frame.word_wrap = True
        hp = hb.text_frame.add_paragraph()
        hp.text = finding.get("heading", f"Finding {i}")
        hp.font.size = PPt(26); hp.font.bold = True; hp.font.color.rgb = _WHITE
        bb = slide.shapes.add_textbox(PInches(0.5), PInches(2), PInches(9), PInches(3.5))
        bb.text_frame.word_wrap = True
        bp = bb.text_frame.add_paragraph()
        bp.text = finding.get("body", "")
        bp.font.size = PPt(16); bp.font.color.rgb = _WHITE

    # Closing slide
    slide = prs.slides.add_slide(prs.slide_layouts[6])
    _set_slide_bg(slide, _SOVEREIGN_BLUE)
    tb = slide.shapes.add_textbox(PInches(1), PInches(2.5), PInches(8), PInches(1))
    p = tb.text_frame.add_paragraph()
    p.text = "Sovereign AI Workbench — 100% On-Device"
    p.font.size = PPt(20); p.font.color.rgb = _SOVEREIGN_ACCENT
    p.alignment = PP_ALIGN.CENTER


PPTX_TEMPLATES = {
    "findings_deck": _pptx_findings_deck,
    "briefing":      _pptx_findings_deck,
}


def generate_pptx(template: str, content: dict[str, Any], filename: str | None = None) -> Path:
    """Generate a .pptx file from a named template + content dict."""
    if template not in PPTX_TEMPLATES:
        template = "findings_deck"
    prs = Presentation()
    prs.slide_width = PInches(10)
    prs.slide_height = PInches(5.625)
    PPTX_TEMPLATES[template](prs, content)
    fname = (filename or f"{template}_{datetime.now().strftime('%Y%m%d_%H%M%S')}") + ".pptx"
    out_path = settings.output_dir / fname
    prs.save(str(out_path))
    logger.success("Generated PPTX: {}", out_path)
    return out_path


