"""
doc_generator.py — Office-file generator tool for Sovereign.

Generates real deliverable files from structured agent output:
  - DOCX: Approval notes, reports, memos
  - PPTX: Presentation slides (findings, summaries)
  - XLSX: Data tables, calculation sheets

All templates are self-contained (no internet required).
Files are saved to settings.output_dir and returned as a path.
"""

from __future__ import annotations

from datetime import datetime
from pathlib import Path
from typing import Any

from fastapi import FastAPI, HTTPException
from fastapi.responses import FileResponse
from loguru import logger
from pydantic import BaseModel

from config import settings

