app = FastAPI(title="Sovereign Document Generator", version="1.0.0")


class DocRequest(BaseModel):
    template: str
    content: dict[str, Any]
    filename: str | None = None


@app.post("/generate/docx")
async def api_docx(req: DocRequest):
    try:
        path = generate_docx(req.template, req.content, req.filename)
        return {"status": "ok", "file": str(path), "filename": path.name}
    except ValueError as e:
        raise HTTPException(400, str(e))
    except Exception as e:
        logger.exception("DOCX generation failed")
        raise HTTPException(500, str(e))


@app.post("/generate/pptx")
async def api_pptx(req: DocRequest):
    try:
        path = generate_pptx(req.template, req.content, req.filename)
        return {"status": "ok", "file": str(path), "filename": path.name}
    except ValueError as e:
        raise HTTPException(400, str(e))
    except Exception as e:
        logger.exception("PPTX generation failed")
        raise HTTPException(500, str(e))


@app.post("/generate/xlsx")
async def api_xlsx(req: DocRequest):
    try:
        path = generate_xlsx(req.template, req.content, req.filename)
        return {"status": "ok", "file": str(path), "filename": path.name}
    except ValueError as e:
        raise HTTPException(400, str(e))
    except Exception as e:
        logger.exception("XLSX generation failed")
        raise HTTPException(500, str(e))


@app.get("/generate/download/{filename}")
async def api_download(filename: str):
    file_path = settings.output_dir / filename
    if not file_path.exists():
        raise HTTPException(404, "File not found")
    return FileResponse(str(file_path), filename=filename)


@app.get("/generate/list")
async def api_list():
    files = [
        {"name": f.name, "size_kb": round(f.stat().st_size / 1024, 1)}
        for f in sorted(settings.output_dir.iterdir(), key=lambda x: x.stat().st_mtime, reverse=True)
        if f.is_file()
    ]
    return {"files": files}


