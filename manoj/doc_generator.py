def _docx_approval_note(doc: Document, content: dict) -> None:
    """Approval Note — used for inspection-report approvals."""
    header = doc.sections[0].header
    hp = header.paragraphs[0]
    hp.text = "SOVEREIGN — CONFIDENTIAL"
    hp.alignment = WD_ALIGN_PARAGRAPH.CENTER
    hp.runs[0].font.size = Pt(8)
    hp.runs[0].font.color.rgb = RGBColor(0x88, 0x88, 0x88)

    title_para = doc.add_heading(content.get("title", "Approval Note"), level=1)
    title_para.alignment = WD_ALIGN_PARAGRAPH.CENTER

    meta_table = doc.add_table(rows=4, cols=2)
    meta_table.style = "Table Grid"
    for i, (label, value) in enumerate([
        ("Reference No.", content.get("ref_no", "SV-" + datetime.now().strftime("%Y%m%d-%H%M"))),
        ("Date",          content.get("date", datetime.now().strftime("%B %d, %Y"))),
        ("Prepared By",   content.get("prepared_by", "Sovereign AI Agent")),
        ("Access Level",  content.get("access_level", "public").upper()),
    ]):
        meta_table.cell(i, 0).text = label
        meta_table.cell(i, 1).text = value
        meta_table.cell(i, 0).paragraphs[0].runs[0].bold = True
    doc.add_paragraph()

    doc.add_heading("Executive Summary", level=2)
    doc.add_paragraph(content.get("summary", ""))

    if content.get("findings"):
        doc.add_heading("Key Findings", level=2)
        for f in content["findings"]:
            doc.add_paragraph(f, style="List Bullet")

    if content.get("sources"):
        doc.add_heading("Source Documents Referenced", level=2)
        for s in content["sources"]:
            doc.add_paragraph(s, style="List Bullet")

    if content.get("recommendation"):
        doc.add_heading("Recommendation / Decision", level=2)
        p = doc.add_paragraph(content["recommendation"])
        p.runs[0].bold = True

    doc.add_paragraph()
    doc.add_paragraph("Approved by: ________________________")
    doc.add_paragraph("Signature:   ________________________")
    doc.add_paragraph(f"Date:        {content.get('date', datetime.now().strftime('%B %d, %Y'))}")

    footer = doc.sections[0].footer
    fp = footer.paragraphs[0]
    fp.text = "Generated by Sovereign AI Workbench — Air-gapped, on-device only."
    fp.alignment = WD_ALIGN_PARAGRAPH.CENTER
    fp.runs[0].font.size = Pt(7)
    fp.runs[0].font.color.rgb = RGBColor(0xAA, 0xAA, 0xAA)


def _docx_generic_report(doc: Document, content: dict) -> None:
    """Generic report template."""
    doc.add_heading(content.get("title", "Report"), level=1)
    doc.add_paragraph(f"Date: {content.get('date', datetime.now().strftime('%B %d, %Y'))}")
    doc.add_paragraph(f"Author: {content.get('author', 'Sovereign AI')}")
    doc.add_paragraph()
    if content.get("summary"):
        doc.add_heading("Executive Summary", level=2)
        doc.add_paragraph(content["summary"])
    for section in content.get("sections", []):
        doc.add_heading(section.get("heading", ""), level=2)
        body = section.get("body", "")
        if isinstance(body, list):
            for item in body:
                doc.add_paragraph(str(item), style="List Bullet")
        else:
            doc.add_paragraph(str(body))
    if content.get("conclusion"):
        doc.add_heading("Conclusion", level=2)
        doc.add_paragraph(content["conclusion"])


DOCX_TEMPLATES = {
    "approval_note":     _docx_approval_note,
    "generic_report":    _docx_generic_report,
    "inspection_report": _docx_generic_report,
}


def generate_docx(template: str, content: dict[str, Any], filename: str | None = None) -> Path:
    """Generate a .docx file from a named template + content dict."""
    if template not in DOCX_TEMPLATES:
        template = "generic_report"
    doc = Document()
    doc.styles["Normal"].font.name = "Calibri"
    doc.styles["Normal"].font.size = Pt(11)
    DOCX_TEMPLATES[template](doc, content)
    fname = (filename or f"{template}_{datetime.now().strftime('%Y%m%d_%H%M%S')}") + ".docx"
    out_path = settings.output_dir / fname
    doc.save(str(out_path))
    logger.success("Generated DOCX: {}", out_path)
    return out_path


