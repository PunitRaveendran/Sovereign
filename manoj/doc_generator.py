_HEADER_FILL  = PatternFill("solid", fgColor="1A1A2E")
_ACCENT_FILL  = PatternFill("solid", fgColor="00D4AA")
_ALT_ROW_FILL = PatternFill("solid", fgColor="F0F7F4")
_HEADER_FONT  = Font(name="Calibri", bold=True, color="FFFFFF", size=11)
_BODY_FONT    = Font(name="Calibri", size=10)
_CENTER       = Alignment(horizontal="center", vertical="center", wrap_text=True)
_LEFT         = Alignment(horizontal="left",   vertical="center", wrap_text=True)
_THIN = Border(
    left=Side(style="thin", color="CCCCCC"), right=Side(style="thin",  color="CCCCCC"),
    top=Side(style="thin",  color="CCCCCC"), bottom=Side(style="thin", color="CCCCCC"),
)


def _xlsx_data_table(wb: openpyxl.Workbook, content: dict) -> None:
    ws = wb.active
    ws.title = content.get("sheet_title", "Data")
    headers = content.get("headers", [])
    rows    = content.get("rows", [])

    # Title row
    end_col = get_column_letter(max(len(headers), 1))
    ws.merge_cells(f"A1:{end_col}1")
    c = ws["A1"]
    c.value = content.get("title", "Data Table")
    c.font  = Font(name="Calibri", bold=True, size=14, color="FFFFFF")
    c.fill  = _HEADER_FILL; c.alignment = _CENTER
    ws.row_dimensions[1].height = 30

    for ci, h in enumerate(headers, 1):
        cell = ws.cell(row=2, column=ci, value=h)
        cell.font = _HEADER_FONT; cell.fill = _ACCENT_FILL
        cell.alignment = _CENTER; cell.border = _THIN
    ws.row_dimensions[2].height = 22

    for ri, row in enumerate(rows, 3):
        fill = _ALT_ROW_FILL if ri % 2 == 0 else PatternFill()
        for ci, val in enumerate(row, 1):
            cell = ws.cell(row=ri, column=ci, value=val)
            cell.font = _BODY_FONT; cell.alignment = _LEFT
            cell.border = _THIN
            if ri % 2 == 0:
                cell.fill = fill
        ws.row_dimensions[ri].height = 18

    for ci, h in enumerate(headers, 1):
        col_vals = [str(row[ci-1]) if ci-1 < len(row) else "" for row in rows]
        max_len = max([len(str(h))] + [len(v) for v in col_vals])
        ws.column_dimensions[get_column_letter(ci)].width = min(max_len + 4, 40)

    meta = wb.create_sheet("Metadata")
    meta["A1"] = "Generated By";  meta["B1"] = "Sovereign AI Workbench"
    meta["A2"] = "Generated At";  meta["B2"] = datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    meta["A3"] = "Air-gapped";    meta["B3"] = "Yes — 100% on-device"


def _xlsx_calculation_sheet(wb: openpyxl.Workbook, content: dict) -> None:
    ws = wb.active
    ws.title = content.get("sheet_title", "Calculations")
    ws.merge_cells("A1:D1")
    ws["A1"].value = content.get("title", "Calculation Sheet")
    ws["A1"].font  = Font(name="Calibri", bold=True, size=14, color="FFFFFF")
    ws["A1"].fill  = _HEADER_FILL; ws["A1"].alignment = _CENTER
    ws.row_dimensions[1].height = 30

    ws["A3"].value = "INPUTS"
    ws["A3"].font  = Font(name="Calibri", bold=True, size=11, color="FFFFFF")
    ws["A3"].fill  = _ACCENT_FILL

    inputs = content.get("inputs", [])
    for i, inp in enumerate(inputs, 4):
        ws.cell(row=i, column=1, value=inp.get("label", "")).font  = _BODY_FONT
        ws.cell(row=i, column=2, value=inp.get("value", "")).font  = _BODY_FONT
        ws.cell(row=i, column=3, value=inp.get("unit",  "")).font  = _BODY_FONT

    rs = len(inputs) + 6
    ws.cell(row=rs, column=1, value="RESULTS").font = Font(bold=True, size=11, color="FFFFFF")
    ws.cell(row=rs, column=1).fill = _ACCENT_FILL

    for j, res in enumerate(content.get("results", []), rs + 1):
        ws.cell(row=j, column=1, value=res.get("label", "")).font  = _BODY_FONT
        ws.cell(row=j, column=2, value=res.get("value", "")).font  = Font(bold=True)
        ws.cell(row=j, column=3, value=res.get("unit",  "")).font  = _BODY_FONT

    for col in ["A", "B", "C", "D"]:
        ws.column_dimensions[col].width = 28


XLSX_TEMPLATES = {
    "data_table":        _xlsx_data_table,
    "metrics":           _xlsx_data_table,
    "calculation_sheet": _xlsx_calculation_sheet,
}


def generate_xlsx(template: str, content: dict[str, Any], filename: str | None = None) -> Path:
    """Generate a .xlsx file from a named template + content dict."""
    if template not in XLSX_TEMPLATES:
        template = "data_table"
    wb = openpyxl.Workbook()
    XLSX_TEMPLATES[template](wb, content)
    fname = (filename or f"{template}_{datetime.now().strftime('%Y%m%d_%H%M%S')}") + ".xlsx"
    out_path = settings.output_dir / fname
    wb.save(str(out_path))
    logger.success("Generated XLSX: {}", out_path)
    return out_path


